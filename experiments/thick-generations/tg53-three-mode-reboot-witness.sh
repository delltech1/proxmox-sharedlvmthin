#!/usr/bin/env bash
set -Eeuo pipefail

# Disposable lab qualification for clean-boundary persistence across a node
# reboot.  prepare creates one stopped VM with one Thin, Eager and Lazy disk,
# writes fsynced canaries, proves an untouched Lazy region reads as zero and
# stores an immutable manifest.  verify must run after a different boot and
# reads every witness before performing any write.  cleanup is explicit and is
# available only after a successful verify receipt exists.

MODE="${1:?usage: $0 prepare|verify|cleanup VMID THIN EAGER LAZY STATE_DIR}"
VMID="${2:?usage: $0 prepare|verify|cleanup VMID THIN EAGER LAZY STATE_DIR}"
THIN="${3:?usage: $0 prepare|verify|cleanup VMID THIN EAGER LAZY STATE_DIR}"
EAGER="${4:?usage: $0 prepare|verify|cleanup VMID THIN EAGER LAZY STATE_DIR}"
LAZY="${5:?usage: $0 prepare|verify|cleanup VMID THIN EAGER LAZY STATE_DIR}"
STATE_DIR="${6:?usage: $0 prepare|verify|cleanup VMID THIN EAGER LAZY STATE_DIR}"

[[ "$MODE" =~ ^(prepare|verify|cleanup)$ ]]
[[ "$VMID" =~ ^[1-9][0-9]{2,8}$ ]]
for storage in "$THIN" "$EAGER" "$LAZY"; do
    [[ "$storage" =~ ^[A-Za-z0-9][A-Za-z0-9_.-]*$ ]]
done
[[ "$STATE_DIR" == /* ]]

umask 077
mkdir -p -- "$STATE_DIR"
manifest="$STATE_DIR/manifest"
verified="$STATE_DIR/verified"
evidence="$STATE_DIR/evidence.log"
exec > >(tee -a "$evidence") 2>&1

die() { echo "REFUSE=$*"; exit 2; }
boot_id() { cat /proc/sys/kernel/random/boot_id; }

config_value() {
    local key="$1"
    qm config "$VMID" | sed -n "s/^${key}: \([^,]*\).*/\1/p"
}

activate() {
    perl -I/usr/share/perl5 -MPVE::Storage -e '
        my ($v)=@ARGV; my $c=PVE::Storage::config();
        PVE::Storage::activate_volumes($c,[$v]);
    ' "$1"
}

deactivate() {
    perl -I/usr/share/perl5 -MPVE::Storage -e '
        my ($v)=@ARGV; my $c=PVE::Storage::config();
        PVE::Storage::deactivate_volumes($c,[$v]);
    ' "$1"
}

read_hash() {
    local vol="$1" offset_mib="$2" path
    activate "$vol" >&2
    path="$(pvesm path "$vol")"
    dd if="$path" bs=1M skip="$offset_mib" count=1 iflag=fullblock status=none \
        | sha256sum | awk '{print $1}'
    deactivate "$vol" >&2
}

write_marker() {
    local vol="$1" offset_mib="$2" marker="$3" path
    activate "$vol" >&2
    path="$(pvesm path "$vol")"
    printf '%s' "$marker" | dd of="$path" bs=1 seek=$((offset_mib * 1024 * 1024)) \
        conv=notrunc,fsync status=none
    deactivate "$vol" >&2
}

lazy_status() {
    local vol="$1" path public_mapper hash clone_mapper status
    activate "$vol" >&2
    path="$(pvesm path "$vol")"
    public_mapper="${path##*/}"
    hash="${public_mapper#sltg-}"
    [[ "$hash" != "$public_mapper" && -n "$hash" ]] || {
        deactivate "$vol" >&2
        die LAZY_PUBLIC_MAPPER_NAME_INVALID
    }
    clone_mapper="sltg-c-$hash"
    status="$(dmsetup status "$clone_mapper")"
    deactivate "$vol" >&2
    printf '%s\n' "$status"
}

load_manifest() {
    [[ -f "$manifest" ]] || die MANIFEST_MISSING
    # The file is generated by this script with shell-escaped values and is
    # root-only.  Reject unknown keys before sourcing it.
    if grep -Evq '^(PREPARE_BOOT|PACKAGE_SHA|CONFIG_SHA|THIN_VOL|EAGER_VOL|LAZY_VOL|THIN_SIZE|EAGER_SIZE|LAZY_SIZE|THIN_SHA_(8|512|1000)|EAGER_SHA_(8|512|1000)|LAZY_SHA_(8|512|1000)|THIN_ZERO_SHA|EAGER_ZERO_SHA|LAZY_ZERO_SHA|ZERO_SHA|LAZY_STATUS)=' "$manifest"; then
        die MANIFEST_SCHEMA_INVALID
    fi
    # shellcheck disable=SC1090
    source "$manifest"
}

case "$MODE" in
prepare)
    [[ ! -e "$manifest" ]] || die MANIFEST_ALREADY_EXISTS
    ! qm config "$VMID" >/dev/null 2>&1 || die VMID_ALREADY_EXISTS
    for storage in "$THIN" "$EAGER" "$LAZY"; do
        pvesm status --storage "$storage" --enabled 1 >/dev/null
    done

    qm create "$VMID" --name "tg53-reboot-witness-$VMID" --memory 64 \
        --cores 1 --ostype l26 --scsihw virtio-scsi-single --onboot 0
    qm set "$VMID" --scsi0 "${THIN}:1,iothread=1"
    qm set "$VMID" --scsi1 "${EAGER}:1,iothread=1"
    qm set "$VMID" --scsi2 "${LAZY}:1,iothread=1"
    [[ "$(qm status "$VMID")" == "status: stopped" ]]

    thin_vol="$(config_value scsi0)"
    eager_vol="$(config_value scsi1)"
    lazy_vol="$(config_value scsi2)"
    [[ "$thin_vol" == "$THIN:"* && "$eager_vol" == "$EAGER:"* && "$lazy_vol" == "$LAZY:"* ]]

    for offset in 8 512 1000; do
        write_marker "$thin_vol" "$offset" "TG53-REBOOT-THIN-$VMID-$offset"
        write_marker "$eager_vol" "$offset" "TG53-REBOOT-EAGER-$VMID-$offset"
        write_marker "$lazy_vol" "$offset" "TG53-REBOOT-LAZY-$VMID-$offset"
    done
    thin_sha_8="$(read_hash "$thin_vol" 8)"
    thin_sha_512="$(read_hash "$thin_vol" 512)"
    thin_sha_1000="$(read_hash "$thin_vol" 1000)"
    eager_sha_8="$(read_hash "$eager_vol" 8)"
    eager_sha_512="$(read_hash "$eager_vol" 512)"
    eager_sha_1000="$(read_hash "$eager_vol" 1000)"
    lazy_sha_8="$(read_hash "$lazy_vol" 8)"
    lazy_sha_512="$(read_hash "$lazy_vol" 512)"
    lazy_sha_1000="$(read_hash "$lazy_vol" 1000)"
    zero_sha="$(dd if=/dev/zero bs=1M count=1 status=none | sha256sum | awk '{print $1}')"
    thin_zero_sha="$(read_hash "$thin_vol" 256)"
    eager_zero_sha="$(read_hash "$eager_vol" 256)"
    lazy_zero_sha="$(read_hash "$lazy_vol" 256)"
    [[ "$thin_zero_sha" == "$zero_sha" && "$eager_zero_sha" == "$zero_sha" && "$lazy_zero_sha" == "$zero_sha" ]]
    thin_size="$(activate "$thin_vol" >&2; blockdev --getsize64 "$(pvesm path "$thin_vol")"; deactivate "$thin_vol" >&2)"
    eager_size="$(activate "$eager_vol" >&2; blockdev --getsize64 "$(pvesm path "$eager_vol")"; deactivate "$eager_vol" >&2)"
    lazy_size="$(activate "$lazy_vol" >&2; blockdev --getsize64 "$(pvesm path "$lazy_vol")"; deactivate "$lazy_vol" >&2)"
    lazy_dm_status="$(lazy_status "$lazy_vol")"
    [[ " $lazy_dm_status " == *" no_hydration "* ]] || die LAZY_BACKGROUND_HYDRATION_ENABLED
    [[ "$lazy_dm_status" == *" clone "* ]] || die LAZY_NOT_CLONE

    config_sha="$(qm config "$VMID" | sha256sum | awk '{print $1}')"
    package_sha="$(sha256sum /usr/share/perl5/PVE/Storage/Custom/SharedLvmThinPlugin.pm | awk '{print $1}')"
    {
        printf 'PREPARE_BOOT=%q\n' "$(boot_id)"
        printf 'PACKAGE_SHA=%q\n' "$package_sha"
        printf 'CONFIG_SHA=%q\n' "$config_sha"
        printf 'THIN_VOL=%q\n' "$thin_vol"
        printf 'EAGER_VOL=%q\n' "$eager_vol"
        printf 'LAZY_VOL=%q\n' "$lazy_vol"
        printf 'THIN_SIZE=%q\n' "$thin_size"
        printf 'EAGER_SIZE=%q\n' "$eager_size"
        printf 'LAZY_SIZE=%q\n' "$lazy_size"
        for offset in 8 512 1000; do
            eval "value=\$thin_sha_$offset"; printf 'THIN_SHA_%s=%q\n' "$offset" "$value"
            eval "value=\$eager_sha_$offset"; printf 'EAGER_SHA_%s=%q\n' "$offset" "$value"
            eval "value=\$lazy_sha_$offset"; printf 'LAZY_SHA_%s=%q\n' "$offset" "$value"
        done
        printf 'THIN_ZERO_SHA=%q\n' "$thin_zero_sha"
        printf 'EAGER_ZERO_SHA=%q\n' "$eager_zero_sha"
        printf 'LAZY_ZERO_SHA=%q\n' "$lazy_zero_sha"
        printf 'ZERO_SHA=%q\n' "$zero_sha"
        printf 'LAZY_STATUS=%q\n' "$lazy_dm_status"
    } >"$manifest.tmp"
    sync "$manifest.tmp"
    mv -n -- "$manifest.tmp" "$manifest"
    sync "$STATE_DIR"
    echo "PREPARE_BOOT=$(boot_id)"
    echo "CONFIG_SHA=$config_sha"
    echo "PACKAGE_SHA=$package_sha"
    echo "THIN_VOL=$thin_vol"
    echo "EAGER_VOL=$eager_vol"
    echo "LAZY_VOL=$lazy_vol"
    echo "LAZY_STATUS=$lazy_dm_status"
    echo "THREE_MODE_REBOOT_PREPARE=PASS"
    ;;

verify)
    [[ ! -e "$verified" ]] || die VERIFY_RECEIPT_ALREADY_EXISTS
    load_manifest
    [[ "$(boot_id)" != "$PREPARE_BOOT" ]] || die REBOOT_UNPROVEN
    [[ "$(qm status "$VMID")" == "status: stopped" ]] || die VM_NOT_STOPPED
    [[ "$(sha256sum /usr/share/perl5/PVE/Storage/Custom/SharedLvmThinPlugin.pm | awk '{print $1}')" == "$PACKAGE_SHA" ]] || die PACKAGE_DRIFT
    [[ "$(qm config "$VMID" | sha256sum | awk '{print $1}')" == "$CONFIG_SHA" ]] || die CONFIG_DRIFT
    [[ "$(config_value scsi0)" == "$THIN_VOL" ]]
    [[ "$(config_value scsi1)" == "$EAGER_VOL" ]]
    [[ "$(config_value scsi2)" == "$LAZY_VOL" ]]

    # These are the first data-path reads after reboot; no write is issued.
    for offset in 8 512 1000; do
        eval "expected=\$THIN_SHA_$offset"; [[ "$(read_hash "$THIN_VOL" "$offset")" == "$expected" ]] || die "THIN_CANARY_MISMATCH_$offset"
        eval "expected=\$EAGER_SHA_$offset"; [[ "$(read_hash "$EAGER_VOL" "$offset")" == "$expected" ]] || die "EAGER_CANARY_MISMATCH_$offset"
        eval "expected=\$LAZY_SHA_$offset"; [[ "$(read_hash "$LAZY_VOL" "$offset")" == "$expected" ]] || die "LAZY_CANARY_MISMATCH_$offset"
    done
    [[ "$(read_hash "$THIN_VOL" 256)" == "$THIN_ZERO_SHA" ]] || die THIN_ZERO_REGION_MISMATCH
    [[ "$(read_hash "$EAGER_VOL" 256)" == "$EAGER_ZERO_SHA" ]] || die EAGER_ZERO_REGION_MISMATCH
    [[ "$(read_hash "$LAZY_VOL" 256)" == "$LAZY_ZERO_SHA" ]] || die LAZY_ZERO_REGION_MISMATCH
    current_thin_size="$(activate "$THIN_VOL" >&2; blockdev --getsize64 "$(pvesm path "$THIN_VOL")"; deactivate "$THIN_VOL" >&2)"
    current_eager_size="$(activate "$EAGER_VOL" >&2; blockdev --getsize64 "$(pvesm path "$EAGER_VOL")"; deactivate "$EAGER_VOL" >&2)"
    current_lazy_size="$(activate "$LAZY_VOL" >&2; blockdev --getsize64 "$(pvesm path "$LAZY_VOL")"; deactivate "$LAZY_VOL" >&2)"
    [[ "$current_thin_size" == "$THIN_SIZE" && "$current_eager_size" == "$EAGER_SIZE" && "$current_lazy_size" == "$LAZY_SIZE" ]] || die SIZE_DRIFT
    lazy_after="$(lazy_status "$LAZY_VOL")"
    [[ " $lazy_after " == *" no_hydration "* ]] || die LAZY_BACKGROUND_HYDRATION_ENABLED_AFTER_REBOOT
    [[ "$lazy_after" == *" clone "* ]] || die LAZY_NOT_CLONE_AFTER_REBOOT

    {
        printf 'VERIFY_BOOT=%q\n' "$(boot_id)"
        printf 'VERIFY_UTC=%q\n' "$(date -u +%FT%TZ)"
        printf 'LAZY_STATUS_AFTER=%q\n' "$lazy_after"
    } >"$verified.tmp"
    sync "$verified.tmp"
    mv -n -- "$verified.tmp" "$verified"
    sync "$STATE_DIR"
    echo "PREPARE_BOOT=$PREPARE_BOOT"
    echo "VERIFY_BOOT=$(boot_id)"
    echo "LAZY_STATUS_BEFORE=$LAZY_STATUS"
    echo "LAZY_STATUS_AFTER=$lazy_after"
    echo "MARKER_HASHES=9/9"
    echo "ZERO_HASHES=3/3"
    echo "THREE_MODE_REBOOT_VERIFY=PASS"
    ;;

cleanup)
    [[ -f "$verified" ]] || die VERIFY_RECEIPT_MISSING
    load_manifest
    [[ "$(qm status "$VMID")" == "status: stopped" ]] || die VM_NOT_STOPPED
    qm destroy "$VMID" --purge 1 --destroy-unreferenced-disks 1
    ! qm config "$VMID" >/dev/null 2>&1 || die VM_STILL_EXISTS
    echo "THREE_MODE_REBOOT_CLEANUP=PASS"
    ;;
esac
